package repository

import (
	"context"
	"time"
	"uuid"

	"github.com/alex8obrien/flow/internal/domain"
	"github.com/alex8obrien/flow/internal/telemetry"
)

type LinkRepository struct {
	db     DB
	tracer telemetry.Tracer
}

const pingTimeout = 2 * time.Second

func NewLinkRepository(db DB, tracer telemetry.Tracer) LinkRepository {
	return LinkRepository{db: db, tracer: tracer}
}

func (r LinkRepository) Ping(ctx context.Context) error {
	ctx, span := r.tracer.Start(ctx, "db.links.ping",
		telemetry.String("db.system", "postgresql"),
		telemetry.String("db.operation", "PING"),
	)
	defer span.End()
	span.AddEvent("db.links.ping.query_start")

	c, cancel := context.WithTimeout(ctx, pingTimeout)
	defer cancel()

	err := r.db.Ping(c)
	if err != nil {
		span.RecordError(err)
		span.AddEvent("db.links.ping.query_failed")
		span.SetStatus(telemetry.StatusError, "ping failed")
		return err
	}

	span.SetStatus(telemetry.StatusSuccess, "ping completed")
	span.AddEvent("db.links.ping.query_completed")

	return nil
}

func (r LinkRepository) Insert(ctx context.Context, link *domain.Link) (*domain.Link, error) {
	ctx, span := r.tracer.Start(ctx, "db.links.insert_link",
		telemetry.String("db.system", "postgresql"),
		telemetry.String("db.operation", "INSERT"),
		telemetry.String("db.sql.table", "links"),
	)
	defer span.End()
	span.AddEvent("db.links.insert_link.query_start")

	var id uuid.UUID
	var clicks int
	var createdAt time.Time

	err := r.db.QueryRow(ctx, "INSERT INTO links (short_code, destination_url, display_name, description) VALUES ($1, $2, $3, $4) RETURNING id, clicks, created_at;", link.ShortCode, link.DestinationURL, link.DisplayName, link.Description).
		Scan(&id, &clicks, &createdAt)
	if err != nil {
		span.RecordError(err)
		span.AddEvent("db.links.insert_link.query_failed")
		span.SetStatus(telemetry.StatusError, "insert query failed")
		return nil, err
	}

	// Update struct with data generated by database
	link.ID = id
	link.Clicks = clicks
	link.CreatedAt = createdAt

	span.SetAttributes(telemetry.String("link.id", link.ID.String()))
	span.SetStatus(telemetry.StatusSuccess, "insert completed")
	span.AddEvent("db.links.insert_link.query_completed")

	return link, nil
}

func (r LinkRepository) FindByShortCode(ctx context.Context, shortCode string) (*domain.Link, error) {
	ctx, span := r.tracer.Start(ctx, "db.links.find_link",
		telemetry.String("db.system", "postgresql"),
		telemetry.String("db.operation", "SELECT"),
		telemetry.String("db.sql.table", "links"),
		telemetry.String("db.links.short_code", shortCode),
	)
	defer span.End()
	span.AddEvent("db.links.find_link.query_start")

	var id uuid.UUID
	var destinationURL string

	err := r.db.QueryRow(
		ctx,
		"UPDATE links SET clicks = clicks + 1 WHERE short_code = $1 RETURNING id, destination_url;",
		shortCode,
	).Scan(&id, &destinationURL)
	if err != nil {
		span.RecordError(err)
		span.AddEvent("db.links.find_link.query_failed")
		span.SetStatus(telemetry.StatusError, "insert query failed")
		return nil, err
	}

	span.SetAttributes(telemetry.String("link.id", id.String()))
	span.SetStatus(telemetry.StatusSuccess, "find link completed")
	span.AddEvent("db.links.find_link.query_completed")

	return &domain.Link{ID: id, DestinationURL: destinationURL}, nil
}
